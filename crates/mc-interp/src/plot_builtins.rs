fn bi_fill(args: &[Value], line: u32, col: u32) -> Result<(), McError> {
    // fill(x1, y1, c1?, x2, y2, c2?, ...) — رنگ هر چندضلعی فقط رشته‌ای
    // ('r' | 'red' | ...)؛ سه‌تایی عددی پذیرفته نمی‌شود چون از xِ جفت بعدی
    // قابل‌تفکیک نیست (متلب خودش با اجباری‌کردن C ابهام را می‌بندد) —
    // رنگ دقیق RGB از مسیر plot(..., 'Color', [r g b]) موجود است.
    let numeric_idx: Vec<usize> = args
        .iter()
        .enumerate()
        .filter(|(_, a)| is_numeric(a))
        .map(|(i, _)| i)
        .collect();
    if numeric_idx.is_empty() || !numeric_idx.len().is_multiple_of(2) {
        return Err(perr(
            line,
            col,
            "fill: numeric arguments must be (x, y) pairs — colors are strings ('r').".into(),
            "fill: آرگومان‌های عددی باید زوج (x, y) باشند — رنگ‌ها رشته‌ای‌اند ('r').".into(),
        ));
    }
    let mut polys: Vec<FillPair> = Vec::new();
    let mut i = 0;
    while i < args.len() {
        if !is_numeric(&args[i]) || i + 1 >= args.len() || !is_numeric(&args[i + 1]) {
            return Err(perr(
                line,
                col,
                "fill: expected (x, y) pairs with optional color string after each.".into(),
                "fill: زوج‌های (x, y) و پس از هرکدام رشتهٔ رنگ اختیاری لازم است.".into(),
            ));
        }
        let x = numeric_vec(&args[i], "fill", line, col)?;
        let y = numeric_vec(&args[i + 1], "fill", line, col)?;
        if x.len() != y.len() || x.is_empty() {
            return Err(perr(
                line,
                col,
                "fill: each polygon needs x and y of equal nonzero length.".into(),
                "fill: هر چندضلعی x و y هم‌طول و ناتهی لازم دارد.".into(),
            ));
        }
        i += 2;
        let mut style = StyleSpec::default();
        if i < args.len() {
            let is_color_char = matches!(&args[i], Value::Char(c) if !matches!(
                c.as_str(),
                "LineWidth" | "Color" | "LineStyle" | "Marker" | "MarkerSize"
                    | "stacked" | "filled" | "DisplayName"
            ));
            if is_color_char {
                style.color = Some(color_value(&args[i], "fill", line, col)?);
                i += 1;
            }
        }
        polys.push(FillPair {
            data: SeriesData { x, y },
            style,
        });
    }
    session::emit(PlotOp::Fill { polys });
    Ok(())
}

