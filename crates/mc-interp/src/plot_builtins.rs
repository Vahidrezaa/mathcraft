/// `stem(x, y, fmt?, 'filled'?)` — سنتز روی اشکال موجود قرارداد: یک سری
/// خط برای رایزها (گپ NaN بین هر رایز) + یک سری فقط-مارکر برای سرها.
fn bi_stem(args: &[Value], line: u32, col: u32) -> Result<(), McError> {
    let (x, ycols, next) = xy_args(args, "stem", line, col)?;
    if ycols.len() != 1 {
        return Err(perr(
            line,
            col,
            "stem: a single y vector is supported (one call per series).".into(),
            "stem: یک بردار y در هر فراخوانی پشتیبانی می‌شود.".into(),
        ));
    }
    let y = ycols.into_iter().next().unwrap_or_default();
    let x = x_or_default(&x, y.len());
    let t = style_from_trailing(args, next, "stem", line, col)?;
    let s = t.style;
    // رایزها: [x, 0] → [x, y] با گپ NaN — رندرر غیرمتناهی را گپ می‌کشد
    let mut rx = Vec::with_capacity(y.len() * 3);
    let mut ry = Vec::with_capacity(y.len() * 3);
    for i in 0..y.len() {
        if !y[i].is_finite() {
            continue;
        }
        rx.extend_from_slice(&[x[i], x[i], f64::NAN]);
        ry.extend_from_slice(&[0.0, y[i], f64::NAN]);
    }
    let riser_style = StyleSpec {
        color: s.color,
        width: s.width,
        dash: s.dash,
        marker: None,
        label: None,
    };
    let head_style = StyleSpec {
        color: s.color,
        width: s.width,
        dash: Some(mc_plot::spec::DashSpec::Invisible),
        marker: Some(s.marker.unwrap_or(mc_plot::spec::MarkerSpec::Circle)),
        label: None,
    };
    session::emit(PlotOp::Line {
        series: vec![
            SeriesPair {
                data: SeriesData { x: rx, y: ry },
                style: riser_style,
            },
            SeriesPair {
                data: SeriesData { x, y },
                style: head_style,
            },
        ],
    });
    Ok(())
}

/// `stairs(x, y, fmt?)` — چندخطی پله‌ای (افقی سپس عمودی؛ پارتی متلب).
fn bi_stairs(args: &[Value], line: u32, col: u32) -> Result<(), McError> {
    let (x, ycols, next) = xy_args(args, "stairs", line, col)?;
    if ycols.len() != 1 {
        return Err(perr(
            line,
            col,
            "stairs: a single y vector is supported (one call per series).".into(),
            "stairs: یک بردار y در هر فراخوانی پشتیبانی می‌شود.".into(),
        ));
    }
    let y = ycols.into_iter().next().unwrap_or_default();
    let x = x_or_default(&x, y.len());
    if x.len() != y.len() || x.is_empty() {
        return Err(perr(
            line,
            col,
            "stairs: x and y must be equal-length nonempty vectors.".into(),
            "stairs: x و y باید هم‌طول و ناتهی باشند.".into(),
        ));
    }
    let t = style_from_trailing(args, next, "stairs", line, col)?;
    let mut sx = Vec::with_capacity(2 * x.len());
    let mut sy = Vec::with_capacity(2 * y.len());
    sx.push(x[0]);
    sy.push(y[0]);
    for i in 1..x.len() {
        sx.push(x[i]);
        sy.push(y[i - 1]);
        sx.push(x[i]);
        sy.push(y[i]);
    }
    session::emit(PlotOp::Line {
        series: vec![SeriesPair {
            data: SeriesData { x: sx, y: sy },
            style: t.style,
        }],
    });
    Ok(())
}

